"""Turns reference/dumps/dialogs.txt into src/QDialogTemplates.m.

The dump is the literal content of the original DIALOG resources, so the
generated table is the original geometry down to the dialog unit.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'reference', 'dumps', 'dialogs.txt')
DST = os.path.join(ROOT, 'src', 'QDialogTemplates.m')

# Dialogs we build, with the C identifier each table gets.
WANTED = {
    100:   'About',
    106:   'OptionsEditor',
    107:   'OptionsBuild',
    141:   'CommandLine',
    142:   'BuildOutput',
    143:   'Examine',
    144:   'Watch',
    145:   'AddWatch',
    162:   'ProjectProperties',
    164:   'Grep',
    165:   'GrepResults',
    168:   'OptionsRun',
    182:   'DebugConsole',
    186:   'Beautifier',
    30721: 'New',
}

CLASS_MAP = {
    'BUTTON': 'QCtlButton',
    'EDIT': 'QCtlEdit',
    'STATIC': 'QCtlStatic',
    'LISTBOX': 'QCtlListBox',
    'COMBOBOX': 'QCtlComboBox',
    'msctls_updown32': 'QCtlSpin',
    'SysTreeView32': 'QCtlTree',
}

DIALOG_RE = re.compile(r'^=== DIALOG (\d+) "(.*)" (\d+)x(\d+) font=(.*) style=(0x[0-9a-f]+)$')
ITEM_RE = re.compile(r'^\s+(\S+)\s+id=(\d+)\s+\((-?\d+),(-?\d+),(-?\d+),(-?\d+)\)\s+st=(0x[0-9a-f]+)\s+"(.*)"\s*$')


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    dialogs = []
    current = None
    for line in open(SRC, encoding='utf-8'):
        line = line.rstrip('\n')
        m = DIALOG_RE.match(line)
        if m:
            did = int(m.group(1))
            current = {'id': did, 'caption': m.group(2),
                       'cx': int(m.group(3)), 'cy': int(m.group(4)),
                       'items': []}
            dialogs.append(current)
            continue
        m = ITEM_RE.match(line)
        if m and current is not None:
            cls = m.group(1)
            if cls not in CLASS_MAP:
                print('skipping unknown control class', cls, file=sys.stderr)
                continue
            cid = int(m.group(2))
            if cid == 4294967295:
                cid = 65535           # the dump prints -1 unsigned
            current['items'].append({
                'cls': CLASS_MAP[cls], 'id': cid,
                'x': int(m.group(3)), 'y': int(m.group(4)),
                'cx': int(m.group(5)), 'cy': int(m.group(6)),
                'style': m.group(7), 'text': m.group(8),
            })

    out = ['//',
           '//  QDialogTemplates.m — generated by tools/mkdialogs.py from',
           '//  reference/dumps/dialogs.txt.  Do not edit by hand.',
           '//',
           '//  Coordinates are dialog units of MS Sans Serif 8, exactly as the',
           '//  original DIALOG resources carry them.',
           '//',
           '',
           '#import "Quincy.h"',
           '']
    emitted = []
    for d in dialogs:
        if d['id'] not in WANTED:
            continue
        name = WANTED[d['id']]
        out.append('static const QDlgItem k%sItems[] = {' % name)
        for it in d['items']:
            out.append('    { %-13s %5d, %4d, %4d, %4d, %4d, %s, %s },' % (
                it['cls'] + ',', it['id'], it['x'], it['y'], it['cx'],
                it['cy'], it['style'], c_string(it['text'])))
        out.append('};')
        out.append('const QDlgTemplate QDlg%s = { %d, %s, %d, %d,'
                   ' k%sItems, (int)(sizeof(k%sItems) / sizeof(QDlgItem)) };'
                   % (name, d['id'], c_string(d['caption']), d['cx'], d['cy'],
                      name, name))
        out.append('')
        emitted.append(name)

    open(DST, 'w', encoding='utf-8').write('\n'.join(out))

    # The matching extern declarations.
    decls = '\n'.join('extern const QDlgTemplate QDlg%s;' % n for n in emitted)
    print(decls)


if __name__ == '__main__':
    main()
